/**
 * Извлекает ASCII-цифры (0-9) из строки, отбрасывая всё остальное.
 *
 * @remarks Матчит только ASCII `0-9` (regex `\D`). Не-ASCII цифры
 * (арабско-индийские ٠١٢, деванагари, полноширинные １２３ и т.п.) считаются
 * не-цифрами и удаляются целиком. Маски по дизайну ориентированы на ASCII-цифры.
 */
export const extractDigits = (str: string): string => str.replace(/\D/g, '');
